def _secret_key_for_environment(debug, configured_key):
    if not configured_key:
        if not debug:
            raise ImproperlyConfigured(
                'SECRET_KEY must be configured when DEBUG is disabled.'
            )
        return 'django-insecure-local-development-key'
    if not debug and (
        len(configured_key) < 50
        or len(set(configured_key)) < 5
        or configured_key.startswith('django-insecure-')
    ):
        raise ImproperlyConfigured(
            'When DEBUG is disabled, SECRET_KEY must be a strong, unique key '
            'of at least 50 characters.'
        )
    return configured_key


def _mailers_for_environment(debug, environ):
    backend = environ.get('EMAIL_BACKEND') or (
        'django.core.mail.backends.console.EmailBackend'
        if debug
        else 'django.core.mail.backends.smtp.EmailBackend'
    )
    default_mailer = {'BACKEND': backend}
    if backend == 'django.core.mail.backends.smtp.EmailBackend':
        use_tls = environ.get('EMAIL_USE_TLS', 'False').lower() == 'true'
        use_ssl = environ.get('EMAIL_USE_SSL', 'False').lower() == 'true'
        username = environ.get('EMAIL_HOST_USER') or None
        password = environ.get('EMAIL_HOST_PASSWORD') or None
        if use_tls and use_ssl:
            raise ImproperlyConfigured('EMAIL_USE_TLS and EMAIL_USE_SSL cannot both be enabled.')
        if bool(username) != bool(password):
            raise ImproperlyConfigured(
                'EMAIL_HOST_USER and EMAIL_HOST_PASSWORD must be configured together.'
            )
        if not debug and username and not (use_tls or use_ssl):
            raise ImproperlyConfigured(
                'Authenticated production SMTP requires TLS or SSL.'
            )
        default_mailer['OPTIONS'] = {
            'host': environ.get('EMAIL_HOST', 'localhost'),
            'port': int(environ.get('EMAIL_PORT', '25')),
            'username': username,
            'password': password,
            'use_tls': use_tls,
            'use_ssl': use_ssl,
        }
    return {'default': default_mailer}


